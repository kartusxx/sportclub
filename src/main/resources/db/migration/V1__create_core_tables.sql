CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30)
);

CREATE TABLE trainers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    specialization VARCHAR(120) NOT NULL
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(40) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT chk_membership_dates CHECK (ends_at > starts_at)
);

CREATE TABLE membership_services (
    membership_id BIGINT NOT NULL REFERENCES memberships(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    PRIMARY KEY (membership_id, service_id)
);

CREATE TABLE class_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id BIGINT NOT NULL REFERENCES trainers(id),
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    service_id BIGINT REFERENCES services(id),
    title VARCHAR(150) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(30) NOT NULL,
    CONSTRAINT chk_session_dates CHECK (ends_at > starts_at)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    class_session_id BIGINT NOT NULL REFERENCES class_sessions(id),
    status VARCHAR(30) NOT NULL,
    booked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attended BOOLEAN
);

CREATE INDEX idx_sessions_starts_at
    ON class_sessions(starts_at);
CREATE INDEX idx_sessions_room_starts
    ON class_sessions(room_id, starts_at);
CREATE INDEX idx_bookings_session_status
    ON bookings(class_session_id, status);

CREATE UNIQUE INDEX uq_active_booking_user_session
    ON bookings(user_id, class_session_id)
    WHERE status IN ('BOOKED', 'CONFIRMED');
